String getSecondFloorStaircase(Offset? loc) {
  if (loc == null) return 'Central Staircase';
  if (loc.dx <= 0.185) return 'Left Wing Staircase';
  if (loc.dx >= 0.820) return 'Right Wing Staircase';
  return 'Central Staircase';
}

